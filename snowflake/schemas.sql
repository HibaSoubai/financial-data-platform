USE ROLE ACCOUNTADMIN;
USE DATABASE FIN_PLATFORM;

CREATE SCHEMA IF NOT EXISTS RAW;
CREATE SCHEMA IF NOT EXISTS STAGING;
CREATE SCHEMA IF NOT EXISTS ANALYTICS;

-- Rôle de travail (principe du moindre privilège : on n'utilise pas ACCOUNTADMIN au quotidien)
CREATE ROLE IF NOT EXISTS FIN_ENGINEER;

GRANT USAGE, OPERATE ON WAREHOUSE FIN_WH TO ROLE FIN_ENGINEER;
GRANT ALL PRIVILEGES ON DATABASE FIN_PLATFORM TO ROLE FIN_ENGINEER;
GRANT ALL PRIVILEGES ON ALL SCHEMAS IN DATABASE FIN_PLATFORM TO ROLE FIN_ENGINEER;
GRANT ALL PRIVILEGES ON FUTURE SCHEMAS IN DATABASE FIN_PLATFORM TO ROLE FIN_ENGINEER;

-- Remplace <MON_UTILISATEUR> par le résultat de : SELECT CURRENT_USER();
GRANT ROLE FIN_ENGINEER TO USER <MON_UTILISATEUR>;