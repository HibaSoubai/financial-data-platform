USE ROLE ACCOUNTADMIN;

CREATE SCHEMA IF NOT EXISTS FIN_PLATFORM.RAW;
CREATE SCHEMA IF NOT EXISTS FIN_PLATFORM.STAGING;
CREATE SCHEMA IF NOT EXISTS FIN_PLATFORM.ANALYTICS;

-- Rôle de travail (principe du moindre privilège)
CREATE ROLE IF NOT EXISTS FIN_ENGINEER;

GRANT USAGE, OPERATE ON WAREHOUSE FIN_WH TO ROLE FIN_ENGINEER;
GRANT ALL PRIVILEGES ON DATABASE FIN_PLATFORM TO ROLE FIN_ENGINEER;
GRANT ALL PRIVILEGES ON ALL SCHEMAS IN DATABASE FIN_PLATFORM TO ROLE FIN_ENGINEER;
GRANT ALL PRIVILEGES ON FUTURE SCHEMAS IN DATABASE FIN_PLATFORM TO ROLE FIN_ENGINEER;

-- Attribue le rôle à l'utilisateur courant, sans taper son nom
SET my_user = CURRENT_USER();
GRANT ROLE FIN_ENGINEER TO USER IDENTIFIER($my_user);