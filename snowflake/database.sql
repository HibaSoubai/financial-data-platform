-- Exécuté avec le rôle ACCOUNTADMIN (administrateur du compte)
USE ROLE ACCOUNTADMIN;

-- Warehouse : petit, s'éteint seul après 60 s d'inactivité
CREATE WAREHOUSE IF NOT EXISTS FIN_WH
  WAREHOUSE_SIZE = 'XSMALL'
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE;

-- Garde-fou de coût : alerte à 80 %, arrêt à 100 % de 5 crédits
CREATE RESOURCE MONITOR IF NOT EXISTS FIN_MONITOR
  WITH CREDIT_QUOTA = 5
  TRIGGERS ON 80 PERCENT DO NOTIFY
           ON 100 PERCENT DO SUSPEND;

ALTER WAREHOUSE FIN_WH SET RESOURCE_MONITOR = FIN_MONITOR;

CREATE DATABASE IF NOT EXISTS FIN_PLATFORM;