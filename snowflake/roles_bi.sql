USE ROLE ACCOUNTADMIN;

CREATE ROLE IF NOT EXISTS FIN_BI_READER;

GRANT USAGE ON WAREHOUSE FIN_WH TO ROLE FIN_BI_READER;
GRANT USAGE ON DATABASE FIN_PLATFORM TO ROLE FIN_BI_READER;
GRANT USAGE ON SCHEMA FIN_PLATFORM.ANALYTICS TO ROLE FIN_BI_READER;
GRANT SELECT ON ALL TABLES IN SCHEMA FIN_PLATFORM.ANALYTICS TO ROLE FIN_BI_READER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA FIN_PLATFORM.ANALYTICS TO ROLE FIN_BI_READER;

SET my_user = CURRENT_USER();
GRANT ROLE FIN_BI_READER TO USER IDENTIFIER($my_user);