USE ROLE FIN_ENGINEER;
USE WAREHOUSE FIN_WH;

CREATE TABLE IF NOT EXISTS FIN_PLATFORM.STAGING.MACRO_INDICATORS_SILVER (
    SERIES_ID  VARCHAR(20),
    OBS_DATE   VARCHAR(10),
    OBS_VALUE  FLOAT
);

CREATE TABLE IF NOT EXISTS FIN_PLATFORM.ANALYTICS.DIM_MACRO_SERIES (
    series_id    VARCHAR(20) PRIMARY KEY,
    description  VARCHAR(200) NOT NULL,
    frequency    VARCHAR(20)  NOT NULL,
    unit         VARCHAR(60)
);

CREATE TABLE IF NOT EXISTS FIN_PLATFORM.ANALYTICS.FACT_MACRO_INDICATORS (
    date_id    NUMBER(8,0) NOT NULL REFERENCES FIN_PLATFORM.ANALYTICS.DIM_DATE (date_id),
    series_id  VARCHAR(20) NOT NULL REFERENCES FIN_PLATFORM.ANALYTICS.DIM_MACRO_SERIES (series_id),
    obs_value  FLOAT,
    PRIMARY KEY (date_id, series_id)
);